// Task 051 — the frontend's Content-Security-Policy, built ONCE from the identity providers' configuration.
//
// Used by:
//   - src/frontend/vite.config.ts → `vite preview` sends this header (the Playwright CSP check, e2e/csp.config.ts);
//   - this script's CLI → docs/deploy/nginx-frontend.conf (the production frontend headers, task 052).
//
// Why each source is there:
//   default-src 'self'        everything else only from our own origin
//   script-src 'self'         the built bundle only — no inline script, no eval (Vite's build emits none)
//   style-src 'self' 'unsafe-inline'
//                             MUI's styling engine (emotion) injects <style> elements and style attributes at run
//                             time. A per-request nonce would remove 'unsafe-inline' but needs the server to put a fresh
//                             nonce into index.html AND into emotion's cache on every load (nginx sub_filter + a
//                             <meta> read at start-up) — left as a follow-up; inline STYLE cannot run code.
//   img-src 'self' data: blob: icons as data: URIs; previews of uploaded images as blob:
//   frame-src blob: <providers> the PDF preview (an <iframe> of a blob:); MSAL's silent renewal (hidden iframes)
//   connect-src 'self' <providers>
//                             the API and the hubs (same origin: CSP Level 3 'self' also matches wss:// to the same
//                             host — a bare "wss:" would allow ANY host, so it is not added); MSAL's token requests
//   font-src 'self' data:     Inter is self-hosted; FullCalendar (Agenda) embeds its icon font as a data: URI
//                             (a font cannot run code)
//   object-src 'none'         no plugins
//   base-uri 'self'           no <base> to another origin
//   form-action 'self' <providers>
//   frame-ancestors 'none'    never framed (clickjacking)
// Provider hosts come from the configuration only — never a wildcard.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** The hosts (https://host) of the ENABLED providers in an Auth:Providers array. */
export function providerOrigins(providers = []) {
  const origins = new Set()
  for (const p of providers) {
    if (!p?.Enabled) continue
    for (const url of [p.Authority, p.MetadataAddress]) {
      if (!url) continue
      const parsed = new URL(url)
      if (parsed.protocol !== 'https:') throw new Error(`Provider ${p.Name}: ${url} is not https`)
      origins.add(parsed.origin)
    }
  }
  return [...origins].sort()
}

/** The CSP header value for the given provider origins. */
export function buildCsp(origins = []) {
  const providers = origins.length ? ` ${origins.join(' ')}` : ''
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    `frame-src blob:${providers}`,
    `connect-src 'self'${providers}`,
    "font-src 'self' data:",
    "object-src 'none'",
    "base-uri 'self'",
    `form-action 'self'${providers}`,
    "frame-ancestors 'none'",
  ].join('; ')
}

/** The other headers the frontend always sends (the API sends its own). */
export const otherHeaders = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
}

function nginxConf(csp) {
  return `# GENERATED by tools/security/csp.mjs from the Auth:Providers configuration (task 051) — do not edit by hand:
#   node tools/security/csp.mjs <appsettings with Auth:Providers> > docs/deploy/nginx-frontend.conf
# Included in the frontend's server block (task 052). HTTPS only; HSTS here because nginx terminates TLS.

add_header Content-Security-Policy "${csp}" always;
${Object.entries(otherHeaders).map(([k, v]) => `add_header ${k} "${v}" always;`).join('\n')}
add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

# the SPA: every route serves index.html, which must never be cached (a new release takes effect at once)
location = /index.html {
    add_header Cache-Control "no-store" always;
    add_header Content-Security-Policy "${csp}" always;
${Object.entries(otherHeaders).map(([k, v]) => `    add_header ${k} "${v}" always;`).join('\n')}
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
}
`
}

// CLI: node tools/security/csp.mjs [appsettings.json] — prints the nginx include for that configuration
const self = fileURLToPath(import.meta.url)
if (process.argv[1] && resolve(process.argv[1]) === self) {
  const file = process.argv[2]
  const providers = file ? (JSON.parse(readFileSync(file, 'utf8')).Auth?.Providers ?? []) : []
  const out = nginxConf(buildCsp(providerOrigins(providers)))
  if (process.argv[3]) writeFileSync(resolve(dirname(self), '..', '..', process.argv[3]), out)
  else process.stdout.write(out)
}

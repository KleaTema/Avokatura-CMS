-- ---------------------------------------------------------------------
-- Case history (Historiku) — the BUSINESS timeline users see in the case.
-- Different from the technical audit log (ash_audit): this one has only
-- meaningful case events, in plain Albanian, with old/new values.
-- Append-only: UPDATE and DELETE are rejected by triggers below.
--
-- event_type values used by the API (keep this list in the code as an enum):
--   DOSSIER_CREATED, CASE_REGISTERED, CASE_CREATED_FROM_PREVIOUS, SENT_TO_HEAD,
--   LAWYER_ASSIGNED, LAWYER_TRANSFERRED, SECONDARY_ASSIGNED, ASSISTANT_ADDED,
--   ASSISTANT_REMOVED, PRIORITY_CHANGED, SUSPENSION_CHANGED, CATEGORY_CHANGED,
--   DELEGATED, INSTITUTION_LINKED, JURIST_ASSIGNED, JUDGE_CHANGED,
--   OBJECT_CHANGED, PARTY_ADDED, PARTY_REMOVED, HEARING_ADDED, HEARING_UPDATED,
--   DOCUMENT_UPLOADED, DOCUMENT_REMOVED, SECURITY_MEASURE_SET,
--   DECISION_RECORDED, DECISION_UPDATED, CASE_CLOSED, DOSSIER_ARCHIVED
-- ---------------------------------------------------------------------
CREATE TABLE case_history_events (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  dossier_id    BIGINT UNSIGNED NOT NULL,
  case_id       BIGINT UNSIGNED NULL,
  event_type    VARCHAR(40)     NOT NULL,
  actor_user_id INT UNSIGNED    NULL COMMENT 'NULL = system (e.g. automatic reminder)',
  occurred_at   DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  summary       VARCHAR(500)    NOT NULL COMMENT 'text shown in the history list',
  details       JSON            NULL COMMENT '{"old":{...},"new":{...}} e.g. previous judge/object',
  PRIMARY KEY (id),
  KEY ix_che_dossier (dossier_id, occurred_at),
  KEY ix_che_case (case_id, occurred_at),
  KEY ix_che_type (event_type, occurred_at),
  CONSTRAINT fk_che_dossier FOREIGN KEY (dossier_id)    REFERENCES dossiers (id),
  CONSTRAINT fk_che_case    FOREIGN KEY (case_id)       REFERENCES cases (id),
  CONSTRAINT fk_che_actor   FOREIGN KEY (actor_user_id) REFERENCES users (id)
) ENGINE=InnoDB COMMENT='Historiku i çështjes (vetëm shtim)';

DELIMITER $$
CREATE TRIGGER trg_che_no_update BEFORE UPDATE ON case_history_events
FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'case_history_events is append-only';
END$$
CREATE TRIGGER trg_che_no_delete BEFORE DELETE ON case_history_events
FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'case_history_events is append-only';
END$$
DELIMITER ;

-- ---------------------------------------------------------------------
-- Notifications (Njoftimet). Operational, not a legal record: a nightly job
-- deletes READ notifications older than 12 months (the history table keeps
-- the facts), so this table never grows without bound.
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id           INT UNSIGNED    NOT NULL,
  notification_type VARCHAR(40)     NOT NULL COMMENT 'NEW_CASE_ASSIGNED, CASE_TRANSFERRED, REMINDER_30D, REMINDER_6M, HEARING_TOMORROW, CHAT_MENTION ...',
  case_id           BIGINT UNSIGNED NULL,
  title             VARCHAR(200)    NOT NULL,
  body              VARCHAR(1000)   NULL,
  link_path         VARCHAR(300)    NULL COMMENT 'relative app route, uses public ids',
  created_at        DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  read_at           DATETIME(3)     NULL,
  PRIMARY KEY (id),
  KEY ix_notif_user_list (user_id, created_at),
  KEY ix_notif_user_unread (user_id, read_at),
  KEY ix_notif_cleanup (read_at),
  CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_notif_case FOREIGN KEY (case_id) REFERENCES cases (id)
) ENGINE=InnoDB COMMENT='Njoftimet';

-- ---------------------------------------------------------------------
-- Reminders already sent (30 days -> lawyer + Kryetari; 6 months -> also
-- Monitoruesi). The background job checks this table so a reminder is sent
-- exactly once per assignment, even if the job runs every hour or twice.
-- ---------------------------------------------------------------------
CREATE TABLE case_reminders (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  case_id       BIGINT UNSIGNED NOT NULL,
  assignment_id BIGINT UNSIGNED NOT NULL COMMENT 'primary assignment the timer started from',
  reminder_type VARCHAR(20)     NOT NULL COMMENT 'DATA_MISSING_30D | DATA_MISSING_6M',
  sent_at       DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_cr_once (assignment_id, reminder_type),
  KEY ix_cr_case (case_id),
  CONSTRAINT ck_cr_type CHECK (reminder_type IN ('DATA_MISSING_30D','DATA_MISSING_6M')),
  CONSTRAINT fk_cr_case       FOREIGN KEY (case_id)       REFERENCES cases (id),
  CONSTRAINT fk_cr_assignment FOREIGN KEY (assignment_id) REFERENCES case_assignments (id)
) ENGINE=InnoDB COMMENT='Kujtesat e dërguara';


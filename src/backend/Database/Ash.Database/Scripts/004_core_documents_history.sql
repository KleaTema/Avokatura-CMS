-- ---------------------------------------------------------------------
-- create_dossier: issues
-- step, so no two requests can ever end with the same code.
--   * code built from the ACTIVE row of dossier_code_formats
--   * random digits from RANDOM_BYTES (cryptographic): codes reveal
--     nothing about how many cases exist and cannot be guessed in order
--   * a duplicate (same random number drawn twice, or two protocol users
--     at the same millisecond) is caught by UNIQUE(unique_code) and a new
--     number is drawn — up to 50 times, then a clear error tells the admin
--     the format has run out of space and needs more digits.
-- API usage: CALL create_dossier(@office, @user, @id, @code) inside the
-- same transaction that inserts the case X/1.
-- ---------------------------------------------------------------------
CREATE PROCEDURE create_dossier(
  IN  p_office_id  SMALLINT UNSIGNED,
  IN  p_user_id    INT UNSIGNED,
  OUT p_dossier_id BIGINT UNSIGNED,
  OUT p_code       VARCHAR(30))
BEGIN
  DECLARE v_format_id TINYINT UNSIGNED;
  DECLARE v_template  VARCHAR(40);
  DECLARE v_digits    TINYINT UNSIGNED;
  DECLARE v_office    VARCHAR(30);
  DECLARE v_attempt   INT DEFAULT 0;
  DECLARE v_dup       TINYINT DEFAULT 0;
  DECLARE CONTINUE HANDLER FOR 1062 SET v_dup = 1;   -- duplicate key

  SELECT id, template, random_digits INTO v_format_id, v_template, v_digits
    FROM dossier_code_formats WHERE is_active = 1;
  IF v_format_id IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'No active dossier code format';
  END IF;
  SELECT code INTO v_office FROM offices WHERE id = p_office_id;

  SET p_dossier_id = NULL;
  WHILE p_dossier_id IS NULL DO
    SET v_attempt = v_attempt + 1;
    IF v_attempt > 50 THEN
      SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Dossier code space nearly full: add a format with more random digits';
    END IF;

    SET p_code = REPLACE(REPLACE(REPLACE(v_template,
          '{YYYY}',   YEAR(UTC_DATE())),
          '{OFFICE}', IFNULL(v_office, '')),
          '{RAND}',   LPAD(CAST(CONV(HEX(RANDOM_BYTES(6)), 16, 10) AS UNSIGNED)
                           MOD CAST(POW(10, v_digits) AS UNSIGNED), v_digits, '0'));
    SET v_dup = 0;
    INSERT INTO dossiers (unique_code, code_format_id, office_id, opened_by)
    VALUES (p_code, v_format_id, p_office_id, p_user_id);
    IF v_dup = 0 THEN
      SET p_dossier_id = LAST_INSERT_ID();
    END IF;
  END WHILE;
END$$
DELIMITER ;

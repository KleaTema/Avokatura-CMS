USE ash_core;

-- ---------------------------------------------------------------------
-- Documents. The FILE lives in object storage (MinIO / S3-compatible),
-- this table holds only its metadata (~400 bytes per row).
--   * Belongs to the DOSSIER (one shared timeline across all levels, as the
--     workflow requires); case_id records the level during which it was added.
--   * storage_key is generated by the API (UUID based), never built from the
--     user's file name -> no path traversal, no name collisions, no leaking
--     party names in storage paths or logs.
--   * sha256 proves the file has not changed since upload (court evidence)
--     and finds duplicates.
--   * scan_status: a file is downloadable only when CLEAN (antivirus).
--   * Never hard-deleted: deleted_at hides it; the object stays under the
--     bucket's retention lock.
-- ---------------------------------------------------------------------
CREATE TABLE documents (
  id                 BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
  public_id          BINARY(16)       NOT NULL DEFAULT (UUID_TO_BIN(UUID(), 1)),
  dossier_id         BIGINT UNSIGNED  NOT NULL,
  case_id            BIGINT UNSIGNED  NULL COMMENT 'level (X/n) active when uploaded',
  document_type_id   TINYINT UNSIGNED NOT NULL,
  other_type_text    VARCHAR(200)     NULL COMMENT 'when type = Tjetër',
  title              VARCHAR(255)     NOT NULL COMMENT 'Emri i dokumentit',
  original_file_name VARCHAR(255)     NOT NULL,
  content_type       VARCHAR(100)     NOT NULL,
  size_bytes         BIGINT UNSIGNED  NOT NULL,
  sha256             BINARY(32)       NOT NULL,
  storage_bucket     VARCHAR(63)      NOT NULL,
  storage_key        VARCHAR(200)     NOT NULL COMMENT 'e.g. 2026/10/<uuid> — opaque',
  scan_status        VARCHAR(10)      NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING | CLEAN | INFECTED | FAILED',
  scanned_at         DATETIME(3)      NULL,
  uploaded_by        INT UNSIGNED     NOT NULL,
  uploaded_at        DATETIME(3)      NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'Data e ngarkimit',
  deleted_at         DATETIME(3)      NULL,
  deleted_by         INT UNSIGNED     NULL,
  delete_reason      VARCHAR(300)     NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_documents_public (public_id),
  UNIQUE KEY uq_documents_object (storage_bucket, storage_key),
  KEY ix_documents_timeline (dossier_id, deleted_at, uploaded_at) COMMENT 'dossier timeline, newest first',
  KEY ix_documents_case (case_id),
  KEY ix_documents_hash (sha256),
  KEY ix_documents_scan (scan_status, uploaded_at),
  CONSTRAINT ck_documents_scan CHECK (scan_status IN ('PENDING','CLEAN','INFECTED','FAILED')),
  CONSTRAINT ck_documents_delete CHECK ((deleted_at IS NULL) = (deleted_by IS NULL)),
  CONSTRAINT fk_documents_dossier FOREIGN KEY (dossier_id)       REFERENCES dossiers (id),
  CONSTRAINT fk_documents_case    FOREIGN KEY (case_id)          REFERENCES cases (id),
  CONSTRAINT fk_documents_type    FOREIGN KEY (document_type_id) REFERENCES document_types (id),
  CONSTRAINT fk_documents_upl     FOREIGN KEY (uploaded_by)      REFERENCES users (id),
  CONSTRAINT fk_documents_del     FOREIGN KEY (deleted_by)       REFERENCES users (id)
) ENGINE=InnoDB COMMENT='Dokumentet (metadata). Skedari ruhet në object storage.';

